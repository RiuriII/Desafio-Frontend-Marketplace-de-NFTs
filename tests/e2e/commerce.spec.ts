test('refresh com resposta do POST pendente recupera o mesmo pedido', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  test.skip(testInfo.project.name !== 'chromium-desktop', 'Recuperação detalhada no desktop')
  await reset(page)
  await startCheckout(page)
  await quote(page)
  await page.evaluate(async () => {
    await fetch('/api/__mock/payment-outcome', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ outcome: 'slow-response-after-create' }) })
  })
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect.poll(() => page.evaluate(() => sessionStorage.getItem('kurio:checkout-attempt:v2:user-collector'))).not.toBeNull()
  await expect(page.getByRole('button', { name: 'Atualizar cotação' })).toBeDisabled()
  const lookup = async () => page.evaluate(async () => {
    const attempt = JSON.parse(sessionStorage.getItem('kurio:checkout-attempt:v2:user-collector') ?? '{}') as { key: string }
    const token = localStorage.getItem('kurio:session-token:v1')
    const response = await fetch(`/api/orders/by-idempotency-key/${attempt.key}`, { headers: { Authorization: `Bearer ${token}` } })
    return response.ok ? (await response.json() as { id: string }).id : null
  })
  await expect.poll(lookup).not.toBeNull()
  const created = await lookup()
  expect(created).not.toBeNull()
  await page.reload()
  await expect(page).toHaveURL(new RegExp(`/orders/${created}$`))
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible()
  const available = await page.evaluate(async () => (await (await fetch('/api/nfts/nft-001')).json() as { available: number }).available)
  expect(available).toBe(9)
})
