import { expect, test, type Page } from '@playwright/test'

async function reset(page: Page) {
  await page.goto('/health')
  await expect(page.getByText('API REST: ok')).toBeVisible()
  await page.evaluate(async () => { const result = await fetch('/api/__mock/reset', { method: 'POST' }); if (!result.ok) throw new Error('Reset falhou') })
}
async function expectNoOverflow(page: Page) { expect(await page.locator('html').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true) }
async function login(page: Page) {
  await page.getByLabel('E-mail').fill('collector@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout/)
}
async function startCheckout(page: Page) {
  await page.goto('/nfts/nft-001')
  await page.getByRole('button', { name: 'COMPRAR' }).click()
  await expect(page).toHaveURL(/\/cart/)
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await login(page)
}
async function quote(page: Page) {
  await expect(page.getByRole('heading', { name: 'Revisão do pedido' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Conectar carteira|Desconectar carteira/ })).toBeVisible()
  if (await page.getByRole('button', { name: 'Conectar carteira', exact: true }).isVisible()) await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText('Conectada:', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Gerar cotação' }).click()
  await expect(page.getByRole('heading', { name: 'Cotação da API' })).toBeVisible()
  await page.getByRole('checkbox', { name: 'Revisei os itens, a carteira e o total.' }).check()
}

