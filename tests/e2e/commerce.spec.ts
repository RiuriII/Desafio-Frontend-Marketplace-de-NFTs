test('cotação antiga, recusa e timeout preservam pedido e carrinho', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  test.skip(testInfo.project.name !== 'chromium-desktop', 'Cenários de falha detalhados no desktop')
  await reset(page)
  await startCheckout(page)
  await quote(page)
  await page.evaluate(async () => { await fetch('/api/__mock/nfts/nft-001', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ priceEth: '1.39' }) }) })
  await expect(page.getByText('A cotação está desatualizada.')).toBeVisible({ timeout: 5_000 })
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
  await page.getByRole('button', { name: 'Atualizar cotação' }).click()
  await page.getByRole('checkbox', { name: 'Revisei os itens, a carteira e o total.' }).check()
  await page.evaluate(async () => { await fetch('/api/__mock/payment-outcome', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ outcome: 'refused' }) }) })
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Pagamento recusado' })).toBeVisible()
  await page.goto('/cart')
  await expect(page.getByText('Emerald Ape #042')).toBeVisible()
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await expect(page).toHaveURL(/\/checkout/)
  await quote(page)
  const attempt = await page.evaluate(() => JSON.parse(sessionStorage.getItem('kurio:checkout-attempt:v2:user-collector') ?? '{}') as { quoteId: string; key: string })
  await page.evaluate(async () => { await fetch('/api/__mock/payment-outcome', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ outcome: 'timeout-after-create' }) }) })
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page).toHaveURL(/\/orders\//)
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible()
  const result = await page.evaluate(async ({ key, quoteId }) => {
    const token = localStorage.getItem('kurio:session-token:v1')
    const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'Idempotency-Key': key }
    const same = await fetch('/api/orders', { method: 'POST', headers, body: JSON.stringify({ quoteId }) })
    const sameOrder = await same.json() as { id: string }
    const conflict = await fetch('/api/orders', { method: 'POST', headers, body: JSON.stringify({ quoteId: 'different-quote' }) })
    return { sameStatus: same.status, sameOrderId: sameOrder.id, conflictStatus: conflict.status }
  }, attempt)
  expect(result.sameStatus).toBe(201)
  expect(result.sameOrderId).toBe(new URL(page.url()).pathname.split('/').at(-1))
  expect(result.conflictStatus).toBe(409)
})

