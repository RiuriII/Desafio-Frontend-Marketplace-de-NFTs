test('galeria, edições e quantidade seguem juntas até o recibo', async ({ page }) => {
  await reset(page)
  await page.goto('/nfts/nft-001')
  await page.getByRole('button', { name: 'Próxima imagem' }).click()
  await expect(page.getByRole('img', { name: 'Emerald Ape #042: detalhe superior' })).toBeVisible()
  await page.getByRole('button', { name: '1/1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Aumentar quantidade' })).toBeDisabled()
  await page.getByRole('button', { name: 'COMPRAR' }).click()
  await expect(page).toHaveURL(/\/cart/)
  await page.goto('/nfts/nft-001')
  await page.getByRole('button', { name: 'Aumentar quantidade' }).click()
  await page.getByRole('button', { name: 'COMPRAR' }).click()
  await expect(page.locator('.cart-item')).toHaveCount(2)
  await expect(page.getByLabel('Quantidade de Emerald Ape #042, edição 1/50', { exact: true })).toHaveValue('2')
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await login(page)
  await quote(page)
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible()
  await expect(page.locator('.confirmation-item')).toHaveCount(2)
  await expect(page.locator('.confirmation-item').filter({ hasText: '1/1 × 1' })).toBeVisible()
  await expect(page.locator('.confirmation-item').filter({ hasText: '1/50 × 2' })).toBeVisible()
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
  const nft = await page.evaluate(async () => await (await fetch('/api/nfts/nft-001')).json() as { available: number; editions: { id: string; available: number }[] })
  expect(nft.available).toBe(7)
  expect(nft.editions.find((edition) => edition.id === 'edition-1')?.available).toBe(0)
  expect(nft.editions.find((edition) => edition.id === 'edition-50')?.available).toBe(4)
})

