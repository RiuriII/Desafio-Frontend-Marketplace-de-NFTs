test('carteira pode ser cadastrada, conectada, editada e removida', async ({ page }) => {
  await resetAndLogin(page)
  await page.getByRole('link', { name: 'Carteiras' }).click()
  await expect(page).toHaveURL(/\/account\/wallets/)
  await page.getByLabel('Endereço da carteira *').fill('invalido')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Endereço inválido' })).toBeVisible()
  const address = '0x1234567890abcdef1234567890abcdef12345678'
  await page.getByLabel('Endereço da carteira *').fill(address)
  await page.getByLabel('Apelido da carteira *').fill('Minha carteira nova')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  const card = page.locator('.account-wallet-card').filter({ hasText: 'Minha carteira nova' })
  await expect(card).toContainText(address)
  await card.getByRole('button', { name: 'Conectar' }).click()
  await expect(card).toContainText('Conectada')
  await page.reload()
  await expect(page.locator('.account-wallet-card').filter({ hasText: 'Minha carteira nova' })).toContainText('Conectada')
  await card.getByRole('button', { name: 'Editar' }).click()
  await page.getByLabel('Apelido da carteira *').fill('Carteira editada')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  const edited = page.locator('.account-wallet-card').filter({ hasText: 'Carteira editada' })
  await expect(edited).toBeVisible()
  await edited.getByRole('button', { name: 'Remover' }).click()
  await expect(edited).toHaveCount(0)
})

test('favorito otimista reverte após falha e persiste quando confirmado', async ({ page }) => {
  await resetAndLogin(page)
  await page.goto('/nfts/nft-001')
  const add = page.getByRole('button', { name: 'Favoritar' })
  await add.click()
  await expect(page.getByRole('button', { name: 'Remover dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  const remove = page.getByRole('button', { name: 'Remover dos favoritos' })
  await expect(remove).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(async () => { const response = await fetch('/api/__mock/favorites/fail-next', { method: 'POST' }); if (!response.ok) throw new Error('Falha ao preparar cenário') })
  await remove.click()
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível atualizar o favorito' })).toBeVisible()
  await expect(remove).toHaveAttribute('aria-pressed', 'true')
  await remove.click()
  await expect(page.getByRole('button', { name: 'Favoritar' })).toHaveAttribute('aria-pressed', 'false')
  await page.goto('/account/profile')
  await expect(page.getByText('Nenhum NFT favoritado ainda.')).toBeVisible()
})

test('checkout valida dados do colecionador antes da cotação', async ({ page }) => {
  await resetAndLogin(page)
  await page.goto('/nfts/nft-001')
  await page.getByRole('button', { name: 'COMPRAR' }).click()
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await expect(page.getByRole('heading', { name: 'Perfil do colecionador' })).toBeVisible()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText('Conectada:', { exact: false })).toBeVisible()
  await page.getByLabel('Nome de exibição *').fill('x')
  await page.getByRole('button', { name: 'Gerar cotação' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Use pelo menos 3 caracteres.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Cotação da API' })).toHaveCount(0)
  await page.getByLabel('Nome de exibição *').fill('Colecionador Teste')
  await page.getByRole('button', { name: 'Gerar cotação' }).click()
  await expect(page.getByRole('heading', { name: 'Cotação da API' })).toBeVisible()
  await page.getByLabel('Observação do colecionador (opcional)').fill('Entregar na carteira principal')
  await expect(page.getByRole('button', { name: 'Confirmar compra' })).toBeDisabled()
  await page.getByRole('button', { name: 'Gerar cotação' }).click()
  await page.getByRole('checkbox', { name: 'Revisei os itens, a carteira e o total.' }).check()
  await page.getByRole('button', { name: 'Confirmar compra' }).click()
  await expect(page).toHaveURL(/\/orders\//)
  await expect(page.getByText('Observação: Entregar na carteira principal')).toBeVisible()
})
