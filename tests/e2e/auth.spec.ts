import { expect, test, type Page } from '@playwright/test'

async function reset(page: Page) {
  await page.goto('/health')
  await expect(page.getByText('API REST: ok')).toBeVisible()
  await page.evaluate(async () => {
    const response = await fetch('/api/__mock/reset', { method: 'POST' })
    if (!response.ok) throw new Error('Reset do mock falhou')
  })
}

test('rota privada exige login, sessão volta após refresh e logout limpa acesso', async ({ page }) => {
  await reset(page)
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByLabel('E-mail').fill('collector@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('senha-errada')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'E-mail ou senha incorretos.' })).toBeVisible()
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/account\/profile/)
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Colecionador Demo')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Colecionador Demo')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect.poll(() => new URL(page.url()).pathname).toBe('/')
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByRole('link', { name: /Criar conta|Crie uma conta/ }).click()
  await expect(page).toHaveURL(/\/register\?redirect=/)
  await page.getByLabel('Nome de usuário').fill('Outra Pessoa')
  await page.getByLabel('E-mail').fill('other@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByLabel('Confirmar senha').fill('Demo12345!')
  await page.getByRole('button', { name: /Criar (conta|perfil)/ }).click()
  await expect(page).toHaveURL(/\/account\/profile/)
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Outra Pessoa')
})

test('cadastro valida campos, conflito e troca de usuário isolam a sessão', async ({ page }) => {
  await reset(page)
  await page.goto('/register')
  await page.getByRole('button', { name: /Criar (conta|perfil)/ }).click()
  await expect(page.getByText('Use pelo menos 3 caracteres.')).toBeVisible()
  await page.getByLabel('Nome de usuário').fill('Nova Pessoa')
  await page.getByLabel('E-mail').fill('collector@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByLabel('Confirmar senha').fill('Demo12345!')
  await page.getByRole('button', { name: /Criar (conta|perfil)/ }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Este e-mail já está cadastrado.' })).toBeVisible()
  await page.getByLabel('E-mail').fill('new@example.test')
  await page.getByRole('button', { name: /Criar (conta|perfil)/ }).click()
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Nova Pessoa')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect.poll(() => new URL(page.url()).pathname).toBe('/')
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('artist@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Artista Demo')
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).not.toHaveValue('Nova Pessoa')
})

test('sessão expirada é recusada na rota privada e preserva destino', async ({ page }) => {
  await reset(page)
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('collector@example.test')
  await page.getByLabel('Senha', { exact: true }).fill('Demo12345!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Nome de exibição *' })).toHaveValue('Colecionador Demo')
  await page.evaluate(async () => {
    const token = localStorage.getItem('kurio:session-token:v1')
    const response = await fetch('/api/__mock/expire-session', { method: 'POST', headers: { Authorization: `Bearer ${token}` } })
    if (!response.ok) throw new Error('Expiração do mock falhou')
  })
  await page.reload()
  await expect(page).toHaveURL(/\/login\?redirect=/)
})
